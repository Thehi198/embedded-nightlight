/* Worst-case DAC offset + gain + INL plus ADC TUE, rounded up:
   tol = ceil(21.4 + 0.005 * n) LSB */
static uint16_t st_tolerance(uint16_t n)
{
    return (uint16_t)((21400U + 5U * n + 999U) / 1000U);
}

static void selftest_step(uint16_t measured)
{
    if (st_pending) {
        uint16_t code = codes[st_idx];
        int16_t  err  = (int16_t)((int32_t)measured - (int32_t)code);
        uint16_t tol  = st_tolerance(code);

        ST_results[st_idx].code     = code;
        ST_results[st_idx].measured = measured;
        ST_results[st_idx].error    = err;
        ST_results[st_idx].tol      = tol;
        ST_results[st_idx].pass     = (uint8_t)((err < 0 ? -err : err) <= (int16_t)tol);

        st_idx++;
        st_pending = 0;
    }

    if (st_idx < ST_N) {
        HAL_DAC_SetValue(&hdac, DAC_CHANNEL_1, DAC_ALIGN_12B_R, codes[st_idx]);
        st_pending = 1;
    } else if (st_pass < 0) {
        uint8_t all = 1;
        for (uint32_t i = 0; i < ST_N; i++) all &= st_results[i].pass;
        st_pass = (int8_t)all;
    }
}
#endif

static float stage(float d, int k) /*Select led stage*/
{
    float s = 3.0f * d - (float)k;
    if (s < 0.0f) s = 0.0f;
    if (s > 1.0f) s = 1.0f;
    return s;
}

static void process_half(const uint16_t *src)
{
    uint32_t sum = 0;
    for (uint32_t i = 0; i < HALF_LEN; i++) {
        sum += src[i];
    }
    uint32_t c = (sum + HALF_LEN / 2U) / HALF_LEN;
    if (c < 1U)    c = 1U;
    if (c > 4095U) c = 4095U; /*Keep R finite and positive or else the log blows up*/

	#if ENABLE_DAC_SELFTEST
		selftest_step((uint16_t)c);
		return;
	#endif

    adc_avg = (uint16_t)c; /*view in debug*/
    pr_ohms = R_DIV_OHMS * (float)(4096U - c) / (float)c; /*calculate ohms of pr*/

    float d = (logf(pr_ohms) - ln_r_bright) / ln_r_span; /*calculate normalized brightness*/
    if (d < 0.0f) d = 0.0f;
    if (d > 1.0f) d = 1.0f;
    darkness = d; /*view in debug*/

    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, (uint32_t)(stage(d, 0) * PWM_MAX + 0.5f));
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, (uint32_t)(stage(d, 1) * PWM_MAX + 0.5f));
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_3, (uint32_t)(stage(d, 2) * PWM_MAX + 0.5f));
}

void HAL_ADC_ConvHalfCpltCallback(ADC_HandleTypeDef *hadc)
{
    if (hadc->Instance == ADC1) process_half(&adc_buffer[0]);
}

void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc)
{
    if (hadc->Instance == ADC1) process_half(&adc_buffer[HALF_LEN]);
}

